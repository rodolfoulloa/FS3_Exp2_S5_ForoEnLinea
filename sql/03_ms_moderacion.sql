CREATE TABLE FORO_REPORTES (
    ID                  NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_CONTENIDO      VARCHAR2(12 CHAR)   NOT NULL CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
    CONTENIDO_ID        NUMBER(19)          NOT NULL,
    RESUMEN_CONTENIDO   VARCHAR2(160 CHAR)  NOT NULL,
    MOTIVO              VARCHAR2(25 CHAR)   NOT NULL
                        CHECK (MOTIVO IN ('SPAM', 'OFENSIVO', 'ACOSO', 'CONTENIDO_INAPROPIADO', 'FUERA_DE_TEMA', 'OTRO')),
    DETALLE             VARCHAR2(300 CHAR),
    REPORTANTE_ID       NUMBER(19)          NOT NULL,
    REPORTANTE_ALIAS    VARCHAR2(20 CHAR)   NOT NULL,
    FECHA               TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO              VARCHAR2(12 CHAR)   DEFAULT 'PENDIENTE' NOT NULL
                        CHECK (ESTADO IN ('PENDIENTE', 'RESUELTO', 'DESCARTADO')),
    RESUELTO_POR_ALIAS  VARCHAR2(20 CHAR),
    RESOLUCION          VARCHAR2(300 CHAR),
    FECHA_RESOLUCION    TIMESTAMP(6)
);

CREATE TABLE FORO_ACCIONES_MODERACION (
    ID                  NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_CONTENIDO      VARCHAR2(12 CHAR)   NOT NULL CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
    CONTENIDO_ID        NUMBER(19)          NOT NULL,
    RESUMEN_CONTENIDO   VARCHAR2(160 CHAR)  NOT NULL,
    ACCION              VARCHAR2(10 CHAR)   NOT NULL CHECK (ACCION IN ('BANEAR', 'RESTAURAR')),
    MOTIVO              VARCHAR2(300 CHAR)  NOT NULL,
    ADMIN_ID            NUMBER(19)          NOT NULL,
    ADMIN_ALIAS         VARCHAR2(20 CHAR)   NOT NULL,
    REPORTES_RESUELTOS  NUMBER(10)          DEFAULT 0 NOT NULL,
    FECHA               TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IX_FORO_REPORTES_ESTADO ON FORO_REPORTES (ESTADO, FECHA);
CREATE INDEX IX_FORO_REPORTES_CONTENIDO ON FORO_REPORTES (TIPO_CONTENIDO, CONTENIDO_ID, ESTADO);

