CREATE TABLE FORO_ROLES (
    ID           NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE       VARCHAR2(30 CHAR)   NOT NULL,
    DESCRIPCION  VARCHAR2(200 CHAR)  NOT NULL,
    CONSTRAINT UK_FORO_ROLES_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE FORO_USUARIOS (
    ID                   NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE               VARCHAR2(100 CHAR)  NOT NULL,
    ALIAS                VARCHAR2(20 CHAR)   NOT NULL,
    EMAIL                VARCHAR2(120 CHAR)  NOT NULL,
    PASSWORD_HASH        VARCHAR2(100 CHAR)  NOT NULL,
    ROL_ID               NUMBER(19)          NOT NULL,
    ACTIVO               NUMBER(1)           DEFAULT 1 NOT NULL CHECK (ACTIVO IN (0, 1)),
    BIOGRAFIA            VARCHAR2(300 CHAR),
    FECHA_REGISTRO       TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    CODIGO_RECUPERACION  VARCHAR2(6 CHAR),
    CODIGO_EXPIRA        TIMESTAMP(6),
    CONSTRAINT UK_FORO_USUARIOS_ALIAS UNIQUE (ALIAS),
    CONSTRAINT UK_FORO_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_FORO_USUARIOS_ROL FOREIGN KEY (ROL_ID) REFERENCES FORO_ROLES (ID)
);

