CREATE TABLE FORO_CATEGORIAS (
    ID           NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE       VARCHAR2(50 CHAR)   NOT NULL,
    DESCRIPCION  VARCHAR2(200 CHAR)  NOT NULL,
    ICONO        VARCHAR2(30 CHAR)   NOT NULL,
    COLOR        VARCHAR2(7 CHAR)    NOT NULL,
    CONSTRAINT UK_FORO_CATEGORIAS_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE FORO_TEMAS (
    ID                   NUMBER(19)           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO               VARCHAR2(150 CHAR)   NOT NULL,
    CONTENIDO            VARCHAR2(2000 CHAR)  NOT NULL,
    CATEGORIA_ID         NUMBER(19)           NOT NULL,
    AUTOR_ID             NUMBER(19)           NOT NULL,
    AUTOR_ALIAS          VARCHAR2(20 CHAR)    NOT NULL,
    ESTADO               VARCHAR2(10 CHAR)    DEFAULT 'ACTIVO' NOT NULL CHECK (ESTADO IN ('ACTIVO', 'BANEADO')),
    MOTIVO_BANEO         VARCHAR2(300 CHAR),
    VISTAS               NUMBER(10)           DEFAULT 0 NOT NULL,
    FECHA_CREACION       TIMESTAMP(6)         DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION  TIMESTAMP(6),
    CONSTRAINT FK_FORO_TEMAS_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES FORO_CATEGORIAS (ID)
);

CREATE TABLE FORO_COMENTARIOS (
    ID            NUMBER(19)           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TEMA_ID       NUMBER(19)           NOT NULL,
    AUTOR_ID      NUMBER(19)           NOT NULL,
    AUTOR_ALIAS   VARCHAR2(20 CHAR)    NOT NULL,
    CONTENIDO     VARCHAR2(1000 CHAR)  NOT NULL,
    ESTADO        VARCHAR2(10 CHAR)    DEFAULT 'ACTIVO' NOT NULL CHECK (ESTADO IN ('ACTIVO', 'BANEADO')),
    MOTIVO_BANEO  VARCHAR2(300 CHAR),
    FECHA         TIMESTAMP(6)         DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_FORO_COMENTARIOS_TEMA FOREIGN KEY (TEMA_ID) REFERENCES FORO_TEMAS (ID)
);

CREATE INDEX IX_FORO_TEMAS_CATEGORIA ON FORO_TEMAS (CATEGORIA_ID, ESTADO);
CREATE INDEX IX_FORO_COMENTARIOS_TEMA ON FORO_COMENTARIOS (TEMA_ID, ESTADO);

