FROM FORO_CATEGORIAS C LEFT JOIN FORO_TEMAS T ON T.CATEGORIA_ID = C.ID AND T.ESTADO = 'ACTIVO'
GROUP BY C.NOMBRE ORDER BY C.NOMBRE;
